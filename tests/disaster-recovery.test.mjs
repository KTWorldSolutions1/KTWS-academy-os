import assert from 'node:assert/strict';
import {mkdtempSync,mkdirSync,cpSync,readFileSync,writeFileSync,rmSync,existsSync} from 'node:fs';
import {join,dirname} from 'node:path';
import {tmpdir} from 'node:os';
import {spawnSync} from 'node:child_process';
import {DatabaseSync} from 'node:sqlite';
import {createHash} from 'node:crypto';
const scratch=mkdtempSync(join(tmpdir(),'academy-recovery-drill-'));
const original=join(scratch,'source'),backup=join(scratch,'backup'),recovered=join(scratch,'restored'),tampered=join(scratch,'tampered');
mkdirSync(original,{recursive:true});mkdirSync(backup,{recursive:true});
const key='a1'.repeat(32),wrongKey='b2'.repeat(32);
Object.assign(process.env,{ACADEMY_TEST:'true',PUBLIC_ORIGIN:'https://academy.test',RECORDS_ENCRYPTION_KEY:key,ACADEMY_DATA_DIR:original});
const {handle}=await import('../dist-server/index.js');
const send=(path,data,cookie)=>handle(new Request('https://academy.test'+path,{method:data?'POST':'GET',headers:{Origin:'https://academy.test','Content-Type':'application/json',...(cookie?{Cookie:cookie}:{})},...(data?{body:JSON.stringify(data)}:{})}));
const json=async p=>{const r=await p;return {status:r.status,body:await r.json(),cookie:r.headers.get('set-cookie')?.split(';')[0]};};
const fake='FICTIONAL-RESTORE-TEST-ONLY-DO-NOT-USE-REAL-STUDENT-DATA';
const digest=b=>createHash('sha256').update(b).digest('hex');
try{
 const initialized=spawnSync(process.execPath,['dist-server/setup-owner.js','owner@test.example'],{env:process.env,encoding:'utf8'});
 assert.equal(initialized.status,0,initialized.stderr);
 const owner=await json(send('/api/auth/activate',{token:initialized.stdout.split('#token=')[1].trim(),password:'recovery drill fictional owner password'}));
 assert.equal(owner.status,200);
 const campuses=['Greensboro','Mansfield','Dallas'].map(name=>({id:crypto.randomUUID(),kind:'campuses',name,status:'Active'}));
 const student={id:crypto.randomUUID(),kind:'students',name:'Fake recovery student',status:'Classroom',campusId:campuses[0].id,sessions:[],documents:[]};
 const second={...student,id:crypto.randomUUID(),name:'Fake Texas student',campusId:campuses[1].id};
 const third={...student,id:crypto.randomUUID(),name:'Fake Dallas student',campusId:campuses[2].id};
 const first=await json(send('/api/records',{records:[...campuses,student,second,third]},owner.cookie));
 assert.equal(first.status,200,JSON.stringify(first.body));
 const form=new FormData();form.set('studentId',student.id);form.set('category','Other');form.set('file',new File([fake],'fake-restore-proof.txt',{type:'text/plain'}));
 const uploaded=await json(handle(new Request('https://academy.test/api/files',{method:'POST',headers:{Origin:'https://academy.test',Cookie:owner.cookie},body:form})));
 assert.equal(uploaded.status,200,JSON.stringify(uploaded.body));
 const snapshot=(await json(send('/api/records',null,owner.cookie))).body.records.find(s=>s.id===student.id);
 assert.equal((await send('/api/records',{records:[{...snapshot,documents:[{...uploaded.body,verified:true}]}]},owner.cookie)).status,200);
 const ciphertextPath=join(original,'files',uploaded.body.key);
 const originalCipher=readFileSync(ciphertextPath);
 assert.equal(originalCipher.includes(Buffer.from(fake)),false,'Encrypted bytes must not contain the document plaintext');
 assert.ok(originalCipher.length>Buffer.byteLength(fake));
 // Local SQLite only: use a consistent VACUUM INTO snapshot, not a live filesystem
 // copy of an open WAL-mode SQLite database.
 const sqlite=new DatabaseSync(join(original,'academy.sqlite'));
 const target=join(backup,'academy.sqlite');
 sqlite.exec("VACUUM INTO '"+target.replaceAll("'","''")+"'");
 sqlite.close();
 cpSync(join(original,'files'),join(backup,'files'),{recursive:true});
 const dbHash=digest(readFileSync(target));
 const fileHash=digest(readFileSync(join(backup,'files',uploaded.body.key)));
 assert.equal(fileHash,digest(originalCipher));
 mkdirSync(recovered,{recursive:true});
 cpSync(target,join(recovered,'academy.sqlite'));
 cpSync(join(backup,'files'),join(recovered,'files'),{recursive:true});
 assert.equal(digest(readFileSync(join(recovered,'academy.sqlite'))),dbHash);
 assert.equal(digest(readFileSync(join(recovered,'files',uploaded.body.key))),fileHash);
 const verifier=`
  import assert from 'node:assert/strict';
  const {handle}=await import('./dist-server/index.js');
  const send=path=>handle(new Request('https://academy.test'+path,{headers:{Cookie:process.env.TEST_COOKIE}}));
  const rows=await send('/api/records');
  assert.equal(rows.status,200,'Restored owner session and D1-equivalent records must remain readable');
  const data=await rows.json();
  assert.equal(data.records.filter(r=>r.kind==='campuses').length,3);
  assert.equal(data.records.filter(r=>r.kind==='students').length,3);
  assert.ok(data.audit.some(x=>x.record_id===process.env.TEST_STUDENT_ID));
  const document=await send('/api/files?key='+encodeURIComponent(process.env.TEST_FILE_KEY));
  if(process.env.EXPECT_FAIL==='true')assert.equal(document.status,503,'Wrong or lost key must fail closed; never silently return corrupted student data');
  else {assert.equal(document.status,200);assert.equal(await document.text(),process.env.TEST_CONTENT);}
  console.log(process.env.EXPECT_FAIL==='true'?'Recovery with wrong key correctly blocked':'Restored school records, audit and encrypted document verified');
 `;
 const run=(dir,cryptoKey,expectFail)=>spawnSync(process.execPath,['--input-type=module','--eval',verifier],{cwd:process.cwd(),encoding:'utf8',env:{...process.env,ACADEMY_DATA_DIR:dir,RECORDS_ENCRYPTION_KEY:cryptoKey,TEST_COOKIE:owner.cookie,TEST_FILE_KEY:uploaded.body.key,TEST_STUDENT_ID:student.id,TEST_CONTENT:fake,EXPECT_FAIL:String(expectFail)}});
 const valid=run(recovered,key,false);
 assert.equal(valid.status,0,valid.stderr+'\n'+valid.stdout);
 const lost=run(recovered,wrongKey,true);
 assert.equal(lost.status,0,lost.stderr+'\n'+lost.stdout);
 mkdirSync(tampered,{recursive:true});
 cpSync(target,join(tampered,'academy.sqlite'));
 cpSync(join(backup,'files'),join(tampered,'files'),{recursive:true});
 const tfile=join(tampered,'files',uploaded.body.key),modified=readFileSync(tfile);
 modified[modified.length-1]^=1;writeFileSync(tfile,modified);
 assert.notEqual(digest(readFileSync(tfile)),fileHash);
 const altered=run(tampered,key,true);
 assert.equal(altered.status,0,altered.stderr+'\n'+altered.stdout);
 console.log('PASS: fictional three-campus local backup and isolated restore, persisted audit, encrypted R2-equivalent data, lost-key failure and tamper detection.');
}finally{rmSync(scratch,{recursive:true,force:true});}
