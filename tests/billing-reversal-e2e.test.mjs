import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
import {spawnSync} from 'node:child_process';
import {DatabaseSync} from 'node:sqlite';
const dir=mkdtempSync(join(tmpdir(),'academy-billing-reversal-'));
process.env.ACADEMY_TEST='true';
process.env.PUBLIC_ORIGIN='https://academy.test';
process.env.RECORDS_ENCRYPTION_KEY='ab'.repeat(32);
process.env.ACADEMY_DATA_DIR=dir;
const {handle}=await import('../dist-server/index.js');
const send=(path,body,cookie)=>handle(new Request('https://academy.test'+path,{method:body?'POST':'GET',headers:{Origin:'https://academy.test','Content-Type':'application/json',...(cookie?{Cookie:cookie}:{})},...(body?{body:JSON.stringify(body)}:{})}));
const response=async r=>({status:r.status,body:await r.json(),cookie:r.headers.get('set-cookie')?.split(';')[0]});
let db;
try{
 const setup=spawnSync(process.execPath,['dist-server/setup-owner.js','school-owner@test.example'],{env:process.env,encoding:'utf8'});
 assert.equal(setup.status,0,setup.stderr);
 const token=setup.stdout.split('#token=')[1].trim(),owner=await response(await send('/api/auth/activate',{token,password:'unique billing e2e test password'}));
 assert.equal(owner.status,200);
 db=new DatabaseSync(join(dir,'academy.sqlite'));
 const student='fictional-nimmons',campus='fictional-greensboro',charge='test-charge',receipt='test-payment';
 const now='2026-11-08T13:00:00.000Z';
 const school={id:campus,kind:'campuses',name:'Greensboro Training Center',status:'Active'};
 const learner={id:student,kind:'students',name:'Fictional Nimmons',status:'Classroom',program:'Class A',campusId:campus};
 for(const row of [school,learner])db.prepare("INSERT INTO records(id,owner,kind,payload,revision,updated) VALUES(?,'academy-owner',?,?,1,?)").run(row.id,row.kind,JSON.stringify(row),now);
 db.prepare("INSERT INTO billing_charges(id,owner,campus,student,amount_cents,description,category,due_date,status,created,created_by) VALUES(?,'academy-owner',?,?,300000,'Training test tuition','Tuition','2026-11-16','Open',?,'school-owner@test.example')").run(charge,campus,student,now);
 db.prepare("INSERT INTO billing_payments(id,owner,campus,student,charge_id,provider,source,amount_cents,status,external_ref,created,created_by,verified_at) VALUES(?,'academy-owner',?,?,?,'Cash','Manual',10000,'Confirmed','TEST-NIMMONS',?,'test-clerk@example.test',?)").run(receipt,campus,student,charge,now,now);
 let read=await response(await send('/api/billing?studentId='+student,null,owner.cookie));
 assert.equal(read.status,200,JSON.stringify(read.body));
 assert.equal(read.body.summary.paidCents,10000);
 assert.equal(read.body.summary.outstandingCents,290000);
 let anon=await response(await send('/api/billing',{action:'reverse-manual',studentId:student,chargeId:charge,paymentId:receipt,reason:'Incorrect fictional training payment entry; no funds received.',confirm:'REVERSE INCORRECT MANUAL PAYMENT'}));
 assert.equal(anon.status,401,'Anonymous user cannot modify billing');
 let incorrect=await response(await send('/api/billing',{action:'reverse-manual',studentId:student,chargeId:charge,paymentId:receipt,reason:'Incorrect fictional training payment entry; no funds received.',confirm:'not approved'},owner.cookie));
 assert.equal(incorrect.status,400,'Explicit reversal confirmation required');
 let reversed=await response(await send('/api/billing',{action:'reverse-manual',studentId:student,chargeId:charge,paymentId:receipt,reason:'Incorrect fictional training payment entry; no funds received.',confirm:'REVERSE INCORRECT MANUAL PAYMENT'},owner.cookie));
 assert.equal(reversed.status,200,JSON.stringify(reversed.body));
 assert.equal(reversed.body.status,'Reversed');
 read=await response(await send('/api/billing?studentId='+student,null,owner.cookie));
 assert.equal(read.body.summary.paidCents,0);
 assert.equal(read.body.summary.outstandingCents,300000);
 assert.equal(read.body.payments[0].voided,true);
 assert.equal(read.body.payments[0].status,'Confirmed','Original record remains intact');
 let repeat=await response(await send('/api/billing',{action:'reverse-manual',studentId:student,chargeId:charge,paymentId:receipt,reason:'Incorrect fictional training payment entry; no funds received.',confirm:'REVERSE INCORRECT MANUAL PAYMENT'},owner.cookie));
 assert.equal(repeat.status,409,'Reversal must be idempotent');
 let voided=await response(await send('/api/billing',{action:'void-charge',studentId:student,chargeId:charge,reason:'Erroneous fictional charge created for training only.',confirm:'VOID INCORRECT CHARGE'},owner.cookie));
 assert.equal(voided.status,200,JSON.stringify(voided.body));
 read=await response(await send('/api/billing?studentId='+student,null,owner.cookie));
 assert.equal(read.body.summary.totalCents,0);
 assert.equal(read.body.summary.outstandingCents,0);
 assert.equal(db.prepare('SELECT COUNT(*) AS n FROM billing_payment_reversals').get().n,1);
 assert.equal(db.prepare('SELECT COUNT(*) AS n FROM billing_charge_voids').get().n,1);
 assert.equal(db.prepare("SELECT COUNT(*) AS n FROM audit WHERE action IN ('Incorrect manual payment reversed','Incorrect tuition charge voided')").get().n,2);
 console.log('PASS: authenticated fictional Nimmons billing end-to-end reverses incorrect manual payment, prevents duplicates, voids test charge and preserves audit history.');
}finally{db?.close();rmSync(dir,{recursive:true,force:true});}
