import assert from 'node:assert/strict';
import {parseDmvEnrollmentRoster,parseSchoolDate,parseNorthCarolinaAddress,intakeMatch,buildIntakeStudent} from '../lib/nc-roster-intake.ts';
const heading='| FIRST_NAME | LAST_NAME | DL_NUMBER | DL_STATE | DATE_OB | START_DATE | END_DATE | Phone Number: | Address: |';
const csv='FIRST_NAME,LAST_NAME,DL_NUMBER,DL_STATE,DATE_OB,START_DATE,END_DATE,Phone Number:,Address:';
const row1='| AVERY | EXAMPLE | 000012345678 | NC | 01/02/1996 | NOVEMBER 02, 2026 | DECEMBER 04, 2026 | 336-555-0101 | 100 Fiction Lane Greensboro NC 27401 |';
const row2='| JAMIE | SAMPLE | 000098765432 | NC | 03/04/1989 | NOVEMBER 02, 2026 | DECEMBER 04, 2026 | 336-555-0102 | 2 Testing Rd High Point NC 27265 |';
const sample=['| North Carolina DMV enrollment report |','','| FIRST_NAME | LAST_NAME | DL_NUMBER | DL_STATE | DATE_OB | START_DATE | END_DATE | Phone Number: | Address: |',
 '|---|---|---|---|---|---|---|---|---|',row1,row2].join('\n');
const parsed=parseDmvEnrollmentRoster(sample);
assert.equal(parsed.rows.length,2);
assert.deepEqual(parsed.issues,[]);
assert.equal(parsed.rows[0].licenseNumber,'000012345678');
assert.equal(parsed.rows[0].dob,'1996-01-02');
assert.equal(parsed.rows[0].startDate,'2026-11-02');
assert.equal(parsed.rows[0].endDate,'2026-12-04');
assert.equal(parsed.rows[0].address,'100 Fiction Lane');
assert.equal(parsed.rows[1].city,'High Point');
assert.equal(parsed.rows[0].issues.length,0);
assert.equal(parseSchoolDate('02/29/2024'),'2024-02-29');
assert.equal(parseSchoolDate('02/30/2024'),'');
assert.equal(parseSchoolDate('NOVEMBER 02, 2026'),'2026-11-02');
assert.match(parseNorthCarolinaAddress('???').issue,/separated/);
assert.equal(parseDmvEnrollmentRoster('garbage').rows.length,0);
const duplicate=parseDmvEnrollmentRoster(sample+'\n'+row1);assert.ok(duplicate.rows[2].issues.some(x=>x.includes('Repeated')));
const row=parsed.rows[0];const existing={id:'old',kind:'students',name:row.name,licenseNumber:row.licenseNumber,licenseState:'NC',dob:row.dob,campusId:'gre'};
assert.equal(intakeMatch(row,[existing],'gre').type,'existing');
assert.equal(intakeMatch(row,[{...existing,dob:'1999-09-09'}],'gre').type,'conflict');
assert.equal(intakeMatch(row,[],'gre').type,'new');
const generated=buildIntakeStudent(row,'gre','cohort',crypto.randomUUID());
assert.equal(generated.kind,'students');
assert.equal(generated.status,'Enrollment pending');
assert.equal(generated.documents.length,0);
assert.equal(generated.licenseNumber,'000012345678');
assert.equal(generated.documentRequests[0].category,'Enrollment agreement');
assert.equal(generated.showBirthdayOnCalendar,false);
assert.ok(!generated.assessments.length&&!generated.sessions.length,'No invented instructional evidence');
console.log('Confidential classroom intake parser validation passed; all values in this test are fictional.');
