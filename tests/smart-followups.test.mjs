import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
import {spawnSync} from 'node:child_process';
import {proposedSchoolFollowups,approvedSchoolFollowup} from '../lib/smart-followups.ts';
import {campusSnapshot} from '../lib/operations.ts';
import {today} from '../lib/training.ts';
const date=today();
const ca={id:'gso',kind:'campuses',name:'Greensboro',status:'Active'};
const cb={id:'mfd',kind:'campuses',name:'Mansfield',status:'Active'};
const cc={id:'dal',kind:'campuses',name:'Dallas',status:'Active'};
const admissions={id:'staffA',kind:'staff',name:'Admissions A',status:'Active',campusIds:[ca.id],accessRole:'Enrollment specialist'};
const mgr={id:'staffB',kind:'staff',name:'Texas Mgr',status:'Active',campusIds:[cb.id,cc.id],accessRole:'Campus manager'};
const lead={id:'lead',kind:'leads',name:'Fictional Lead',status:'Contacted',campusId:ca.id,followUp:date,owner:'Admissions'};
const pending={id:'student',kind:'students',name:'Fictional Trainee',status:'Enrollment pending',campusId:cb.id,sessions:[]};
const records=[ca,cb,cc,admissions,mgr,lead,pending];
const suggestions=proposedSchoolFollowups(records,date);
const focus=suggestions.find(s=>s.signal.record.id===lead.id);
assert.ok(focus);
assert.deepEqual(focus.candidateStaff.map(s=>s.id),[admissions.id]);
const work=approvedSchoolFollowup(focus,admissions,records,date,'work-1');
assert.equal(work.signalKey,focus.key);
assert.equal(work.staffId,admissions.id);
assert.equal(work.operationsCase,true);
assert.equal(work.campusId,ca.id);
assert.ok(work.owner);
assert.ok(work.plan.includes('Review'));
assert.throws(()=>approvedSchoolFollowup(focus,mgr,records,date,'wrong'),/not approved|same campus/);
assert.equal(proposedSchoolFollowups([...records,work],date).some(x=>x.key===focus.key),false,'Do not propose duplicate task while open');
const across=campusSnapshot(records,date);
assert.equal(across.length,3);
assert.ok(across.some(x=>x.name==='Greensboro'));
assert.ok(across.some(x=>x.name==='Mansfield'));
assert.ok(across.some(x=>x.name==='Dallas'));
process.env.ACADEMY_TEST='true';process.env.PUBLIC_ORIGIN='https://academy.test';process.env.RECORDS_ENCRYPTION_KEY='99'.repeat(32);process.env.ACADEMY_DATA_DIR=mkdtempSync(join(tmpdir(),'academy-smart-followup-'));
const {handle}=await import('../dist-server/index.js');
const send=(path,data,cookie)=>handle(new Request('https://academy.test'+path,{method:data?'POST':'GET',headers:{Origin:'https://academy.test','Content-Type':'application/json',...(cookie?{Cookie:cookie}:{})},...(data?{body:JSON.stringify(data)}:{})}));
const json=async p=>{const r=await p;return {status:r.status,body:await r.json(),cookie:r.headers.get('set-cookie')?.split(';')[0]};};
try{
 const setup=spawnSync(process.execPath,['dist-server/setup-owner.js','owner@test.example'],{env:process.env,encoding:'utf8'});assert.equal(setup.status,0,setup.stderr);
 const owner=await json(send('/api/auth/activate',{token:setup.stdout.split('#token=')[1].trim(),password:'test owner longer passphrase for automated school'},undefined));
 assert.equal(owner.status,200);
 const liveA={...ca,id:crypto.randomUUID()},liveB={...cb,id:crypto.randomUUID()},liveC={...cc,id:crypto.randomUUID()};
 const staffA={...admissions,id:crypto.randomUUID(),campusIds:[liveA.id],email:'admissions@test.example'};
 const staffB={...mgr,id:crypto.randomUUID(),campusIds:[liveB.id,liveC.id]};
 const leadA={...lead,id:crypto.randomUUID(),campusId:liveA.id};
 const data=await json(send('/api/records',{records:[liveA,liveB,liveC,staffA,staffB,leadA]},owner.cookie));
 assert.equal(data.status,200,JSON.stringify(data.body));
 const invite=await json(send('/api/accounts/invite',{staffId:staffA.id},owner.cookie));assert.equal(invite.status,200);
 const enrolled=await json(send('/api/auth/activate',{token:invite.body.link.split('#token=')[1],password:'test admissions employee passphrase'}));
 assert.equal(enrolled.status,200);
 const current=(await json(send('/api/records',null,owner.cookie))).body.records;
 const proposal=proposedSchoolFollowups(current,date).find(x=>x.signal.record.id===leadA.id);
 assert.ok(proposal);
 const approved=approvedSchoolFollowup(proposal,staffA,current,date,crypto.randomUUID());
 assert.equal((await send('/api/records',{records:[approved]},enrolled.cookie)).status,403,'Employee cannot silently approve school automation.');
 assert.equal((await send('/api/records',{records:[{...approved,id:crypto.randomUUID(),staffId:staffB.id,owner:staffB.name}]},owner.cookie)).status,400,'Owner cannot assign a Greensboro task to a Mansfield-only employee.');
 assert.equal((await send('/api/records',{records:[approved]},owner.cookie)).status,200);
 assert.equal((await send('/api/records',{records:[{...approved,id:crypto.randomUUID()}]},owner.cookie)).status,409,'Server rejects duplicate open case signals.');
 console.log('PASS: three-campus control snapshot, manager-reviewed task ownership and cross-campus/duplicate protections.');
}finally{rmSync(process.env.ACADEMY_DATA_DIR,{recursive:true,force:true});}
