import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
import {spawnSync} from 'node:child_process';
import {DatabaseSync} from 'node:sqlite';
import {DEMO_SCENES,DEMO_RUNTIME_SECONDS,DEMO_SCENE_DURATIONS} from '../lib/presentation-demo.ts';
import {chapterDetail,validateOwnerReview,exportReviewCsv} from '../lib/owner-demo-review.ts';
assert.ok(DEMO_RUNTIME_SECONDS>600,'Owner walkthrough must not race through 27 topics');
assert.ok(DEMO_SCENE_DURATIONS.every(x=>x>=22000));
assert.ok(DEMO_SCENES.every(x=>chapterDetail(x.id).capabilities.length===3),'Every chapter needs meaningful three-part capabilities');
