assert.ok(!validateOwnerReview({chapter:'unknown',type:'Missing feature',priority:'Must have before launch',comment:'This improvement is absolutely needed.'})?.includes('comment'), 'Reject unknown chapters');
const review={chapter:'payments',type:'Missing feature',priority:'Must have before launch',comment:'Owners require one click to compare actual invoice and reconciled tuition.'};
assert.equal(validateOwnerReview(review),null);
assert.match(validateOwnerReview({...review,comment:'Student email joe@example.com should be added'})||'',/identifiers/i);
assert.ok(exportReviewCsv([{...review,id:'1',reviewer:'admin',status:'New',created_at:'2026-11-08',updated_at:'2026-11-08'}]).includes('payments'));
const dir=mkdtempSync(join(tmpdir(),'academy-owner-review-'));
process.env.ACADEMY_TEST='true';process.env.PUBLIC_ORIGIN='https://academy.test';process.env.RECORDS_ENCRYPTION_KEY='98'.repeat(32);process.env.ACADEMY_DATA_DIR=dir;
const {handle}=await import('../dist-server/index.js');
const request=(path,body,cookie)=>handle(new Request('https://academy.test'+path,{method:body?'POST':'GET',headers:{Origin:'https://academy.test',...(body?{'Content-Type':'application/json'}:{}),...(cookie?{Cookie:cookie}:{})},...(body?{body:JSON.stringify(body)}:{})}));
const response=async r=>({status:r.status,body:await r.json(),cookie:r.headers.get('set-cookie')?.split(';')[0]});
let db;
try{
 const setup=spawnSync(process.execPath,['dist-server/setup-owner.js','owner-feedback@test.example'],{env:process.env,encoding:'utf8'});
 assert.equal(setup.status,0,setup.stderr);
 const owner=await response(await request('/api/auth/activate',{token:setup.stdout.split('#token=')[1].trim(),password:'unique owner demo feedback test password'}));
 assert.equal(owner.status,200);
 db=new DatabaseSync(join(dir,'academy.sqlite'));
 assert.equal((await response(await request('/api/demo-feedback'))).status,401,'Anonymous feedback is private');
 let invalid=await response(await request('/api/demo-feedback',{action:'create',...review,comment:'Too short'},owner.cookie));
 assert.equal(invalid.status,400);
 const saved=await response(await request('/api/demo-feedback',{action:'create',...review},owner.cookie));
 assert.equal(saved.status,200,JSON.stringify(saved.body));
 const loaded=await response(await request('/api/demo-feedback',null,owner.cookie));
 assert.equal(loaded.status,200);assert.equal(loaded.body.reviews.length,1);
 assert.equal(loaded.body.reviews[0].comment,review.comment);
 assert.equal(loaded.body.canManage,true);
 const id=saved.body.id;
 const status=await response(await request('/api/demo-feedback',{action:'status',id,status:'Accepted'},owner.cookie));
 assert.equal(status.status,200);
 assert.equal(db.prepare('SELECT status FROM academy_demo_feedback WHERE id=?').get(id).status,'Accepted');
 assert.equal((await response(await request('/api/demo-feedback',{action:'status',id,status:'Bogus'},owner.cookie))).status,400);
 const managerial={id:crypto.randomUUID(),kind:'staff',name:'Fictional Campus Manager',email:'campus-review@test.example',status:'Active',accessRole:'Campus manager',campusIds:['fictional-campus']};
 db.prepare("INSERT INTO records(id,owner,kind,payload,revision,updated) VALUES(?,'academy-owner','staff',?,1,?)").run(managerial.id,JSON.stringify(managerial),'2026-11-08T19:00:00Z');
 const invite=await response(await request('/api/accounts/invite',{staffId:managerial.id},owner.cookie));assert.equal(invite.status,200);
 const manager=await response(await request('/api/auth/activate',{token:invite.body.link.split('#token=')[1],password:'unique campus review test password'}));assert.equal(manager.status,200);
 const mine=await response(await request('/api/demo-feedback',{action:'create',...review,chapter:'yard',comment:'Please add an instructor override report for yard instruction.'},manager.cookie));
 assert.equal(mine.status,200,JSON.stringify(mine.body));
 const readManager=await response(await request('/api/demo-feedback',null,manager.cookie));
 assert.equal(readManager.body.reviews.length,1,'Manager can see only own comments');
 assert.equal(readManager.body.canManage,false);
 const deny=await response(await request('/api/demo-feedback',{action:'status',id:mine.body.id,status:'Accepted'},manager.cookie));
 assert.equal(deny.status,403,'Manager cannot finalize owner review decisions');
 console.log('PASS: slow multi-scene review, real authenticated feedback persistence, leader approval, and campus-level privacy.');
}finally{db?.close();rmSync(dir,{recursive:true,force:true});}
