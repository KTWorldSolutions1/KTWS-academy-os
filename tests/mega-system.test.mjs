import assert from 'node:assert/strict';
import {proposedBiweeklyStarts,classEnding,rosterGaps,studentRosterCsv,FUNDING_TYPES} from '../lib/compliance-roster.ts';
import {documentChecklist,profilePhotoKey,safeStudentDocuments} from '../lib/student-documents.ts';
import {createZip} from '../lib/zip-packet.ts';
import {summarizeKnowledgeAssessments,cohortKnowledgeSignals} from '../lib/learning-diagnostics.ts';
import {createReviewedDiagnostic} from '../lib/quiz-generator.ts';
import {assignmentIssue} from '../lib/assignment-workflow.ts';
import {megaCampusDemoRecords} from '../lib/mega-demo-data.ts';
import {DEMO_SCENES,DEMO_FRAME_MS} from '../lib/presentation-demo.ts';
const dates=proposedBiweeklyStarts();
assert.deepEqual(dates.slice(0,3),['2026-11-16','2026-11-30','2026-12-14']);
assert.equal(classEnding('2026-11-16'),'2026-12-18');
assert.ok(FUNDING_TYPES.includes('WRLP'));
const klass={id:'class',campusId:'gre',startDate:'2026-11-16',endDate:'2026-12-18'};
const student={id:'student',kind:'students',classId:'class',campusId:'gre',name:'\u0027=HYPERLINK(x)',licenseNumber:'TEST-000',dob:'1998-03-01',phone:'555-010-0100',address:'1 Mock Lane',city:'Mockville',state:'NC',zip:'00000',
 documents:[{key:'key1',category:'Enrollment agreement',name:'Test signed agreement.pdf',verified:true},{key:'p',category:'Student profile photo',verified:false}],documentRequests:[{category:'Driver license',status:'Requested'}]};
assert.deepEqual(rosterGaps(student,klass),[]);
assert.ok(rosterGaps({...student,licenseNumber:''},klass).some(x=>x.includes('driver license')));
assert.ok(rosterGaps({...student,documents:[]},klass).some(x=>x.includes('enrollment')));
assert.match(studentRosterCsv(klass,[student]),/\u0027=HYPERLINK/);
assert.equal(profilePhotoKey(student),null);
assert.equal(profilePhotoKey({...student,documents:[...student.documents,{key:'approvedphoto',category:'Student profile photo',verified:true}]}),'approvedphoto');
assert.ok(documentChecklist(student).some(x=>x.category==='Enrollment agreement'&&x.status==='Verified'));
assert.ok(safeStudentDocuments(student).every(x=>!('key' in x)));
const zip=createZip([{name:'test.csv',data:new TextEncoder().encode('one,two\r\n')},{name:'enrollment.pdf',data:new TextEncoder().encode('%PDF-test')}]);
assert.deepEqual([...zip.slice(0,4)],[80,75,3,4]);
assert.equal([...zip].slice(-22,-18).join(','),'80,75,5,6');
const row={id:'s',assessments:[{itemResults:[{subject:'General Knowledge',objective:'Stopping',correct:false},{subject:'Air Brakes',objective:'Pressure',correct:true}]}]};
assert.equal(summarizeKnowledgeAssessments(row)[0].percent,0);
assert.equal(cohortKnowledgeSignals([row])[0].objectives[0].name,'Stopping');
const c={id:'g',kind:'campuses',status:'Active'},a={id:'staff',kind:'staff',status:'Active',campusIds:['g']},task={id:'task',kind:'tasks',name:'Task',campusId:'g',assignedTo:'staff'};
assert.equal(assignmentIssue(task,[c,a]),null);
assert.match(assignmentIssue({...task,campusId:'elsewhere'},[c,a]),/active campus|does not have access/);
const bank={id:'bank',kind:'quizzes',status:'Active',campusId:'g',program:'Class A',questions:Array.from({length:3},(_,i)=>({id:'q'+i,prompt:'Which is the safe option '+i+'?',subject:'Air Brakes',objective:'Air system',options:['Incorrect','Correct'],correct:'1'}))};
assert.equal(createReviewedDiagnostic([bank], 'g','Class A','Air Brakes',3).questions.length,3);
assert.throws(()=>createReviewedDiagnostic([], 'g','Class A','Air Brakes'),/at least three/);
const demo=megaCampusDemoRecords();
assert.equal(demo.filter(r=>r.kind==='students').length,98);
assert.equal(demo.filter(r=>r.kind==='leads'&&r.status==='Funding pending').length,50);
assert.equal(new Set(demo.filter(r=>r.kind==='students').map(r=>r.campusId)).size,3);
assert.equal(new Set(demo.filter(r=>r.kind==='students').map(r=>r.status)).size,8);
assert.ok(DEMO_SCENES.length>=17,'Full current school workflow coverage must be present');
assert.equal(new Set(DEMO_SCENES.map(s=>s.id)).size,DEMO_SCENES.length);
assert.ok(DEMO_SCENES.every(s=>s.destination&&s.narration&&s.highlights.length===3));
assert.ok(DEMO_FRAME_MS>=4500);
assert.equal(demo.filter(r=>r.kind==='leads'&&r.status==='Funding pending').length,50);
assert.ok(demo.every(r=>r.kind!=='students'||!r.ssn));
