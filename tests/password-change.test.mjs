import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
import {spawnSync} from 'node:child_process';
process.env.ACADEMY_TEST='true';process.env.PUBLIC_ORIGIN='https://academy.test';process.env.RECORDS_ENCRYPTION_KEY='dd'.repeat(32);process.env.ACADEMY_DATA_DIR=mkdtempSync(join(tmpdir(),'academy-password-change-'));
const {handle}=await import('../dist-server/index.js');
const send=(path,data,cookie,origin='https://academy.test')=>handle(new Request('https://academy.test'+path,{method:data?'POST':'GET',headers:{Origin:origin,'Content-Type':'application/json',...(cookie?{Cookie:cookie}:{})},...(data?{body:JSON.stringify(data)}:{})}));
const json=async p=>{const r=await p;return {status:r.status,body:await r.json(),cookie:r.headers.get('set-cookie')?.split(';')[0],clear:r.headers.get('set-cookie')}};
try{
 const setup=spawnSync(process.execPath,['dist-server/setup-owner.js','owner@test.example'],{env:process.env,encoding:'utf8'});
 assert.equal(setup.status,0,setup.stderr);
 const orig='long unique owner password for testing';
 const newPassword='strongly changed academy owner password for test';
 const owner=await json(send('/api/auth/activate',{token:setup.stdout.split('#token=')[1].trim(),password:orig}));
 assert.equal(owner.status,200);
 const attempt={currentPassword:orig,newPassword};
 assert.equal((await send('/api/account/password',attempt)).status,401);
 assert.equal((await send('/api/account/password',attempt,owner.cookie,'https://offsite.test')).status,403);
 assert.equal((await send('/api/account/password',{...attempt,currentPassword:'wrong'},owner.cookie)).status,403);
 assert.equal((await send('/api/account/password',{...attempt,newPassword:'short'},owner.cookie)).status,400);
 const ownerChanged=await json(send('/api/account/password',attempt,owner.cookie));
 assert.equal(ownerChanged.status,200,JSON.stringify(ownerChanged.body));
 assert.equal(ownerChanged.body.reloginRequired,true);
 assert.match(ownerChanged.clear,/Max-Age=0/);
 assert.equal((await send('/api/records',null,owner.cookie)).status,401);
 assert.equal((await send('/api/auth/login',{email:'owner@test.example',password:orig})).status,401);
 const relog=await json(send('/api/auth/login',{email:'owner@test.example',password:newPassword}));
 assert.equal(relog.status,200,JSON.stringify(relog.body));
 const campus={id:crypto.randomUUID(),kind:'campuses',name:'Greensboro',status:'Active'};
 const staff={id:crypto.randomUUID(),kind:'staff',name:'Campus administrator',status:'Active',accessRole:'Admin assistant',email:'admin@test.example',campusIds:[campus.id]};
 assert.equal((await send('/api/records',{records:[campus,staff]},relog.cookie)).status,200);
 const inv=await json(send('/api/accounts/invite',{staffId:staff.id},relog.cookie));assert.equal(inv.status,200);
 const staffOrig='unique staff login password for tests',staffNew='new staff password for academy portal';
 const active=await json(send('/api/auth/activate',{token:inv.body.link.split('#token=')[1],password:staffOrig}));assert.equal(active.status,200);
 assert.equal((await send('/api/records',null,active.cookie)).status,200);
 assert.equal((await json(send('/api/account/password',{currentPassword:staffOrig,newPassword:staffNew},active.cookie))).status,200);
 assert.equal((await send('/api/records',null,active.cookie)).status,401);
 assert.equal((await send('/api/auth/login',{email:staff.email,password:staffOrig})).status,401);
 const staffReturn=await json(send('/api/auth/login',{email:staff.email,password:staffNew}));
 assert.equal(staffReturn.status,200);
 assert.equal((await send('/api/records',null,staffReturn.cookie)).status,200);
 const records=(await json(send('/api/records',null,relog.cookie))).body;
 assert.ok(records.audit.some(x=>x.action==='Password changed'&&x.actor==='owner@test.example'));
 assert.ok(records.audit.some(x=>x.action==='Password changed'&&x.actor==='admin@test.example'));
 assert.ok(!JSON.stringify(records.audit).includes(staffNew));
 assert.ok(!JSON.stringify(records.audit).includes(newPassword));
 console.log('PASS: role-safe password change, old-password validation, origin denial, global session revocation, staff self-service and metadata-only audit.');
}finally{rmSync(process.env.ACADEMY_DATA_DIR,{recursive:true,force:true});}
