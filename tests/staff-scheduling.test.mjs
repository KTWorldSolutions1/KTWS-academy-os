import assert from 'node:assert/strict';
import {paidShiftHours,validateStaffShift,staffShiftConflicts,weekDates,weekStart,plannedPaidHours} from '../lib/staff-scheduling.ts';
assert.equal(weekStart('2026-10-14'),'2026-10-12');
assert.equal(weekDates('2026-10-14')[4],'2026-10-16');
const standard={start:'08:00',end:'17:00',breakMinutes:60};
assert.equal(paidShiftHours(standard),8);
assert.equal(paidShiftHours({start:'09:00',end:'16:00',breakMinutes:60}),6);
assert.equal(paidShiftHours({start:'09:00',end:'16:00',breakMinutes:420}),NaN);
const base={id:'shift-1',kind:'shifts',name:'Test shift',status:'Approved',employeeId:'staff-one',campusId:'greensboro',date:'2026-10-12',...standard};
assert.equal(validateStaffShift(base),null);
assert.match(validateStaffShift({...base,start:'17:00',end:'08:00'}),/hours/);
assert.match(validateStaffShift({...base,status:'Paid'}),/status/);
assert.match(validateStaffShift({...base,date:'2026-02-30'}),/date/);
assert.equal(staffShiftConflicts({...base,id:'shift-2',start:'16:00',end:'17:00'},[base]).length,1);
assert.equal(staffShiftConflicts({...base,id:'shift-2',date:'2026-10-13'},[base]).length,0);
assert.equal(staffShiftConflicts({...base,id:'shift-2',status:'Cancelled'},[base]).length,0);
const rows=weekDates('2026-10-14').slice(0,5).map((date,i)=>({...base,id:'s'+i,date}));
assert.equal(plannedPaidHours(rows,'staff-one','2026-10-14'),40);
assert.equal(plannedPaidHours(rows,'staff-other','2026-10-14'),0);
console.log('PASS: weekly shift calculations, 40-hour coverage, break deductions, invalid inputs, overlaps and cancelled shifts.');
