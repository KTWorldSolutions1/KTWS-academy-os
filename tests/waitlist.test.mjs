import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
import {spawnSync} from 'node:child_process';
import {waitingApplicants,waitlistClassOverview,validateWaitlist} from '../lib/waitlist.ts';
const sample={kind:'enrollments',id:'queue-a',name:'Sample application',status:'Waitlisted',leadId:'person-a',classId:'class-a',campusId:'gso'};
assert.equal(validateWaitlist(sample),null);
assert.match(validateWaitlist({...sample,leadId:''}),/existing lead/);
assert.deepEqual(waitingApplicants([{...sample,waitlistedAt:'2026-10-12T12:00:00Z'},{...sample,id:'queue-b',leadId:'person-b',waitlistedAt:'2026-10-13T12:00:00Z'}],'class-a').map(x=>x.application.id),['queue-a','queue-b']);
process.env.ACADEMY_TEST='true';
process.env.PUBLIC_ORIGIN='https://academy.test';
process.env.RECORDS_ENCRYPTION_KEY='aa'.repeat(32);
process.env.ACADEMY_DATA_DIR=mkdtempSync(join(tmpdir(),'academy-waitlist-'));
const {handle}=await import('../dist-server/index.js');
const send=(path,data,cookie)=>handle(new Request('https://academy.test'+path,{method:data?'POST':'GET',headers:{Origin:'https://academy.test','Content-Type':'application/json',...(cookie?{Cookie:cookie}:{})},...(data?{body:JSON.stringify(data)}:{})}));
const json=async promise=>{const response=await promise;return {status:response.status,body:await response.json(),cookie:response.headers.get('set-cookie')?.split(';')[0]};};
try{
 const setup=spawnSync(process.execPath,['dist-server/setup-owner.js','owner@test.example'],{env:process.env,encoding:'utf8'});
 assert.equal(setup.status,0,setup.stderr);
 const owner=await json(send('/api/auth/activate',{token:setup.stdout.split('#token=')[1].trim(),password:'unique school owner password for acceptance'}));
 assert.equal(owner.status,200,JSON.stringify(owner.body));
 const gso={id:crypto.randomUUID(),kind:'campuses',name:'Greensboro',status:'Active'};
 const mansfield={...gso,id:crypto.randomUUID(),name:'Mansfield'};
 const dallas={...gso,id:crypto.randomUUID(),name:'Dallas'};
 const klass={id:crypto.randomUUID(),kind:'classes',name:'Greensboro CDL Class A',status:'Open for enrollment',campusId:gso.id,program:'Class A',startDate:'2026-11-02',endDate:'2026-11-27',capacity:1};
 const texas={...klass,id:crypto.randomUUID(),name:'Mansfield CDL Class A',campusId:mansfield.id};
 const person={id:crypto.randomUUID(),kind:'leads',name:'Fictional Candidate A',status:'Ready to enroll',campusId:gso.id,email:'candidate-a@test.example',owner:'Admissions'};
 const person2={...person,id:crypto.randomUUID(),name:'Fictional Candidate B',email:'candidate-b@test.example'};
 const foreign={...person,id:crypto.randomUUID(),name:'Texas Fictional Candidate',campusId:mansfield.id};
 const employee={id:crypto.randomUUID(),kind:'staff',name:'Admissions Team',email:'admissions@test.example',status:'Active',accessRole:'Enrollment specialist',campusIds:[gso.id]};
 const initial=await json(send('/api/records',{records:[gso,mansfield,dallas,klass,texas,person,person2,foreign,employee]},owner.cookie));
 assert.equal(initial.status,200,JSON.stringify(initial.body));
 const invite=await json(send('/api/accounts/invite',{staffId:employee.id},owner.cookie));assert.equal(invite.status,200);
 const staff=await json(send('/api/auth/activate',{token:invite.body.link.split('#token=')[1],password:'unique admissions staff password'}));assert.equal(staff.status,200);
 const application={id:'queue-a',kind:'enrollments',name:'Fictional Candidate A — application',status:'Waitlisted',leadId:person.id,classId:klass.id,campusId:gso.id,fundingMethod:'Pending authorization',checks:{},studentId:crypto.randomUUID()};
 const created=await json(send('/api/records',{records:[application]},staff.cookie));
 assert.equal(created.status,200,JSON.stringify(created.body));
 const saved=(await json(send('/api/records',null,staff.cookie))).body.records.find(x=>x.id===application.id);
 assert.equal(saved.status,'Waitlisted');
 assert.equal(saved.waitlistedBy,'admissions@test.example');
 assert.ok(saved.waitlistedAt);
 assert.equal((await send('/api/records',{records:[{...application,id:'queue-a-duplicate'}]},staff.cookie)).status,409);
 assert.equal((await send('/api/records',{records:[{...application,id:'forged-date',waitlistedAt:'2020-01-01T00:00:00Z',leadId:person2.id}]},staff.cookie)).status,403);
 assert.equal((await send('/api/records',{records:[{...application,id:'wrong-class',classId:texas.id,leadId:person2.id}]},staff.cookie)).status,400);
 assert.equal((await send('/api/records',{records:[{...application,id:'wrong-lead',leadId:foreign.id}]},staff.cookie)).status,400);
 assert.equal((await send('/api/records',{records:[{...saved,waitlistedBy:'forged@test.example'}]},staff.cookie)).status,403);
 const second=await json(send('/api/records',{records:[{...application,id:'queue-b',name:'Fictional Candidate B — application',leadId:person2.id,studentId:crypto.randomUUID()}]},staff.cookie));
 assert.equal(second.status,200,JSON.stringify(second.body));
 const all=(await json(send('/api/records',null,staff.cookie))).body.records;
 const queue=waitingApplicants(all,klass.id);
 assert.equal(queue.length,2);
 assert.deepEqual(queue.map(x=>x.application.id),['queue-a','queue-b']);
 const summary=waitlistClassOverview(all,klass.id);
 assert.equal(summary?.seatsAvailable,1,'A waiting person has not reserved the class seat');
 assert.equal(summary?.waiting,2);
 assert.equal((await send('/api/records',{records:[{...saved,status:'Application review'}]},staff.cookie)).status,200);
 const reopened=(await json(send('/api/records',null,staff.cookie))).body.records.find(x=>x.id==='queue-a');
 assert.equal(reopened.waitlistedAt,saved.waitlistedAt,'Queue history remains attached to original application');
 assert.equal(waitingApplicants((await json(send('/api/records',null,staff.cookie))).body.records,klass.id).length,1);
 console.log('PASS: evidence-backed admissions waitlists have no reserved seats, no campus bleed, immutable queue timestamps, duplicate protection and explicit human review.');
}finally{rmSync(process.env.ACADEMY_DATA_DIR,{recursive:true,force:true});}
