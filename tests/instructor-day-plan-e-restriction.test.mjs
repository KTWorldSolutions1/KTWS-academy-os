import assert from 'node:assert/strict';
import {instructorDayPlan,instructorWeekPlan} from '../lib/instructor-day-plan.ts';
import {E_RESTRICTION_PROGRAM,eRestrictionReadiness,eRestrictionCompletion} from '../lib/e-restriction-removal.ts';
const monday=instructorDayPlan(1);
assert.equal(monday.blocks.length,5);
assert.equal(monday.blocks[0].start,'07:00');
assert.equal(monday.plannedTeachingHours,10);
assert.equal(monday.availableClockHours,8);
assert.equal(monday.overflowHours,2);
assert.ok(monday.warnings.some(x=>x.includes('do not record unworked hours')));
const week=instructorWeekPlan();
assert.equal(week.plannedHours,50);
assert.equal(week.availableHours,40);
assert.equal(week.unallocatedRequiredHours,10);
assert.equal(week.completeTopicCoverage,true);
assert.throws(()=>instructorDayPlan(6));
assert.equal(E_RESTRICTION_PROGRAM.initialEldtRequired,false);
assert.equal(E_RESTRICTION_PROGRAM.standardFiveWeekCohort,false);
const candidate={cdlVerified:true,hasERestriction:true,dmvRequirementsVerified:false,drivingAuthorized:false,manualVehicleReady:true,instructorAssigned:true,skillsCompleted:[],dmvTestPassed:false,updatedCdlVerified:false};
assert.equal(eRestrictionReadiness(candidate).readyForPublicRoadTraining,false);
const trained={...candidate,dmvRequirementsVerified:true,drivingAuthorized:true,skillsCompleted:E_RESTRICTION_PROGRAM.skills.map(x=>x.id),dmvTestPassed:true,updatedCdlVerified:true};
assert.equal(eRestrictionReadiness(trained).readyForPublicRoadTraining,true);
assert.equal(eRestrictionCompletion(trained).complete,true);
