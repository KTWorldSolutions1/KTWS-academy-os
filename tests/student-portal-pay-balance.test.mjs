import assert from 'node:assert/strict';
import {calculateStudentLedger,publicBillingSummary} from '../lib/student-payments.ts';
import {readFileSync} from 'node:fs';
const charge={id:'charge-1',student:'student-1',campus:'gre',amount_cents:300000,description:'Tuition',category:'Tuition',due_date:'2026-12-01',status:'Open'};
const pending={id:'pay-pending',charge_id:charge.id,student:charge.student,campus:charge.campus,provider:'Cash',source:'Manual',amount_cents:50000,status:'Pending',refunded_cents:0,disputed_cents:0};
const ledger=publicBillingSummary(calculateStudentLedger([charge],[pending]));
assert.equal(ledger.outstandingCents,300000);
assert.equal(ledger.charges[0].paymentPending,true);
const confirmed=publicBillingSummary(calculateStudentLedger([charge],[{...pending,status:'Confirmed'}]));
assert.equal(confirmed.outstandingCents,250000);
assert.equal(confirmed.charges[0].paymentPending,false);
const portal=readFileSync(new URL('../app/student-portal.tsx',import.meta.url),'utf8');
assert.match(portal,/Pay my balance/);
assert.match(portal,/payCharge\(payableCharges\[0\]\.id\)/);
assert.match(portal,/c\.paymentPending/);
assert.match(portal,/Refresh balance/);
const checkout=readFileSync(new URL('../app/api/student/billing/route.ts',import.meta.url),'utf8');
assert.match(checkout,/!config\.ready\|\|config\.testMode/);
assert.match(checkout,/SELECT \* FROM billing_charges WHERE id=\? AND owner='academy-owner' AND student=\? AND campus=\?/);
const studentDemo=readFileSync(new URL('../app/demo-student-portal.tsx',import.meta.url),'utf8');
assert.match(studentDemo,/DEMONSTRATION ONLY · NO REAL MONEY/);
assert.match(studentDemo,/Pay my balance · Demo/);
const tour=readFileSync(new URL('../app/operator-demo.tsx',import.meta.url),'utf8');
assert.match(tour,/portalClick\('Payments'\)/);
console.log('PASS: student Pay My Balance portal, pending-payment protections and fake-money preview.');
