import assert from 'node:assert/strict';
import {overlappingTrainingSession,validateRecord,instructionHours} from '../lib/training.ts';
const student={id:'fictional',kind:'students',name:'Fictional student',status:'Yard',sessions:[]};
const session=(id,phase,start,end,hours,extra={})=>({id,phase,date:'2026-10-14',start,end,hours,breakMinutes:0,attendance:'Present',instructor:'Test instructor',mode:phase==='Road'?'Student driving':'Instruction',mood:'green',...extra});
const a=session('a','Classroom','09:00','11:00',2);
const b=session('b','Yard','10:00','12:00',2);
const overlapping={...student,sessions:[a,b]};
assert.deepEqual(overlappingTrainingSession(overlapping),{first:'a',second:'b',date:'2026-10-14'});
assert.match(validateRecord(overlapping),/Overlapping training sessions/);
const adjacent={...student,sessions:[a,session('next','Yard','11:00','12:00',1)]};
assert.equal(validateRecord(adjacent),null);
const moved={...student,sessions:[a,session('next','Yard','09:00','10:00',1,{date:'2026-10-15'})]};
assert.equal(validateRecord(moved),null);
const correction=session('ac','Classroom','08:00','09:00',1,{correctionOf:'a',correctionReason:'Correct original shift times'});
const corrected={...student,sessions:[a,b,correction]};
assert.equal(overlappingTrainingSession(corrected),null);
assert.equal(validateRecord(corrected),null);
assert.equal(instructionHours(corrected),3);
console.log('PASS: daily logs reject double-booking across phases; adjacent, different-day and audited correction records remain valid.');
