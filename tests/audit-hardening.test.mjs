import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {tprIdentityIssues} from '../lib/tpr-identity-match.ts';
import {anonymousEvidence} from '../lib/ai-evidence.ts';
import {weeklyCampusMinutes} from '../lib/payroll-intervals.ts';
const src=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const student={name:'Example Alex Taylor',clpState:'NC',program:'Class A CDL'};
const f={firstName:'Alex',lastName:'Taylor',state:'US-NC',classCode:'A'};
assert.deepEqual(tprIdentityIssues(student,f),[],'Valid student identity is not blocked');
assert.match(tprIdentityIssues(student,{...f,lastName:'Another'}).join(' '),/names must match/);
assert.match(tprIdentityIssues(student,{...f,state:'VA'}).join(' '),/Issuing state/);
assert.match(tprIdentityIssues(student,{...f,classCode:'B'}).join(' '),/Training class/);
const malicious='John Doe +1 555-555-1212, License S12345 / my secret notes';
const [item]=anonymousEvidence([{kind:'students',name:malicious,status:malicious,phase:malicious}]);
assert.deepEqual(item,{citation:'R1',kind:'students',status:'Other',phase:'Other'});
assert.ok(!JSON.stringify(item).includes('Doe'));
const [safe]=anonymousEvidence([{kind:'fleet',status:'Ready',phase:'Yard'}]);
assert.deepEqual(safe,{citation:'R1',kind:'fleet',status:'Ready',phase:'Yard'});
const monday='2026-11-02',from='2026-11-08T23:00:00.000Z',to='2026-11-09T07:00:00.000Z';
const overnight=[{id:'1',action:'clock_in',at:from,campus_id:'greensboro'},{id:'2',action:'clock_out',at:to,campus_id:'greensboro'}];
assert.equal(weeklyCampusMinutes(overnight,monday).totals.greensboro,360,'Sunday shift split at Eastern Monday midnight');
assert.equal(weeklyCampusMinutes(overnight,'2026-11-09').totals.greensboro,120);
const clock=src('app/api/timeclock/route.ts');
assert.match(clock,/pending clock corrections/,'Cannot lock payroll while a correction is awaiting review');
assert.match(clock,/weeklyCampusMinutes\(rows,week\)/,'Approval must account for local week intervals');
assert.match(clock,/timeZone:'America\/New_York'/,'Live clock uses Eastern calendar week');
const correction=src('app/api/punch-corrections/route.ts');
assert.match(correction,/source_campus_id/,'Manager correction reads must filter by authorized work campus');
assert.match(correction,/c\.access\.campusIds\.includes\(r\.source_campus_id\)/);
assert.ok(correction.includes('week IN (?,?)'),'Correction review must validate both original and proposed locked payroll weeks');
const search=src('app/api/academy-search/route.ts');
assert.match(search,/anonymousEvidence\(matches\)/,'External AI input cannot contain freeform school fields');
assert.match(search,/evidenceMetadataSentToAI:true/,'Provider request must be disclosed even after provider failure');
const federal=src('app/api/tpr/submit/route.ts');
assert.match(federal,/tprIdentityIssues\(student,f\)/,'FMCSA transmission must validate student identity');
assert.match(federal,/TPR_WEB_SERVICE_ENABLED/,'FMCSA live transmitter remains fail-closed');
console.log('PASS audit hardening: identity matching, AI redaction, payroll cutoffs, approvals, manager correction privacy, federal gate.');
