import assert from 'node:assert/strict';
import {calendarEntries,monthDay,studentFacingNotices,validateCalendarRecord} from '../lib/school-calendar.ts';
import {studentJourney,currentJourneyStage} from '../lib/student-journey.ts';
import {MESSAGE_TEMPLATES,expandMessageTemplate,checkBatchRequest} from '../lib/student-messaging.ts';
import {availableSchoolSections} from '../lib/simple-navigation.ts';
const campus={id:'campus-gso',kind:'campuses',name:'Greensboro',state:'NC',status:'Active'};
const d={id:'student',kind:'students',campusId:campus.id,status:'Waiting for permit',name:'Demo Student',dob:'2000-11-07',program:'Class A',documents:[],sessions:[],assessments:[]};
assert.equal(currentJourneyStage(d),1);
assert.equal(studentJourney(d,[campus]).stageName,'Permit preparation');
assert.ok(studentJourney({...d,status:'Road'},[campus]).stageIndex>studentJourney(d,[campus]).stageIndex);
assert.equal(monthDay('2000-02-29'),'02-29');assert.equal(monthDay('2001-02-29'),null);
const announcement={id:'announce',kind:'announcements',campusId:campus.id,status:'Published',name:'Weather check',body:'Please check the classroom schedule before travel.',priority:'Important',audience:'Students',startDate:'2026-11-07',endDate:'2026-11-09',publishOnPortal:true};
const closure={id:'closure',kind:'closures',campusId:campus.id,status:'Confirmed',name:'Weather closure',body:'The Greensboro campus will be closed due to severe weather.',reason:'Weather',startDate:'2026-11-07',endDate:'2026-11-07',publishOnPortal:true};
assert.equal(validateCalendarRecord(announcement),null);
assert.equal(validateCalendarRecord(closure),null);
assert.equal(studentFacingNotices([announcement,closure],campus.id,'2026-11-07').length,2);
assert.deepEqual(studentFacingNotices([announcement,closure],campus.id,'2026-11-10'),[]);
assert.equal(studentFacingNotices([announcement,closure], 'different-campus','2026-11-07').length,0);
assert.equal(studentFacingNotices([{...announcement,status:'Draft'},closure],campus.id,'2026-11-07').length,1);
assert.equal(studentFacingNotices([{...announcement,audience:'Staff'},closure],campus.id,'2026-11-07').length,1);
assert.ok(validateCalendarRecord({...announcement,endDate:'2026-11-06'}));
assert.ok(validateCalendarRecord({...closure,status:'Cancelled',reason:'Invalid'}));
const records=[campus,d,announcement,closure,{id:'staff',kind:'staff',name:'Demo Instructor',campusIds:[campus.id],status:'Active',birthdayMonthDay:'11-07',birthdayCalendarOptIn:true}];
const dateEntries=calendarEntries(records,2026,11);assert.equal(dateEntries.filter(e=>e.category==='Student birthday').length,1);
assert.equal(dateEntries.filter(e=>e.category==='Staff birthday').length,1);
assert.equal(dateEntries.filter(e=>e.category==='Closure').length,1);
const anonymized=expandMessageTemplate('Hi {{firstName}} — {{studentName}} @ {{campusName}}',d,campus);
assert.equal(anonymized,'Hi Demo — Demo Student @ Greensboro');
assert.equal(MESSAGE_TEMPLATES.length>=4,true);
const request={action:'preview',studentIds:['student-a'],channel:'Email',subject:'School notice',body:'Hi {{firstName}}',batchId:'batch-aaaaaaaaaaa'};
assert.equal(checkBatchRequest(request),null);
assert.ok(checkBatchRequest({...request,studentIds:Array(26).fill('student-a')}));
assert.ok(checkBatchRequest({...request,action:'send',confirmSend:false}));
assert.ok(checkBatchRequest({...request,channel:'SMS',body:'X'.repeat(481)}));
const pages=availableSchoolSections('Owner').flatMap(s=>s.pages.map(p=>p.id));
for(const p of ['student-communications','student-id-studio','calendar','school-notices','student-portal-preview'])assert.ok(pages.includes(p),p+' must be discoverable');
assert.equal(pages.length,new Set(pages).size,'Sidebar should not have duplicate routes');
const instructor=availableSchoolSections('Instructor').flatMap(s=>s.pages.map(p=>p.id));
assert.ok(!instructor.includes('student-communications'));
console.log('Student journey, campus closure announcements, private birthday calendar and opt-in message validation passed');
